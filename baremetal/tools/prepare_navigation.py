"""Prepare reviewed original SeedSigner navigation classes for frozen MicroPython.

Extract whole classes from the pinned original app, remove runtime-only type
annotations, and replace Destination's dataclass-generated constructor explicitly.
No View routing methods, equality semantics or sensitive-data redaction are changed.
"""
import ast
import hashlib
import json
from pathlib import Path
import subprocess
root=Path(__file__).resolve().parents[1];repo=root.parent
source=repo/'dist/firmware/sources/lvgl/application'
lock=json.loads((repo/'firmware/lvgl-app/sources.lock.json').read_text())['application']
assert subprocess.check_output(['git','rev-parse','HEAD'],cwd=source,text=True).strip()==lock['commit']
paths={'Destination':source/'src/seedsigner/views/view.py','BackStack':source/'src/seedsigner/controller.py'}
class Types(ast.NodeTransformer):
    def visit_FunctionDef(self,node):
        node.returns=None
        for arg in [*node.args.posonlyargs,*node.args.args,*node.args.kwonlyargs]:arg.annotation=None
        return self.generic_visit(node)
    def visit_AnnAssign(self,node):
        return ast.copy_location(ast.Assign(targets=[node.target],value=node.value),node) if node.value is not None else None
nodes=[];provenance={}
for name,path in paths.items():
    raw=path.read_bytes();tree=ast.parse(raw)
    node=next(n for n in tree.body if isinstance(n,ast.ClassDef) and n.name==name)
    original=ast.get_source_segment(raw.decode(),node)
    provenance[name]={'source':str(path.relative_to(source)),'fileSha256':hashlib.sha256(raw).hexdigest(),'classSha256':hashlib.sha256(original.encode()).hexdigest()}
    node.decorator_list=[]
    if name=='Destination':
        fields=[n for n in node.body if isinstance(n,ast.AnnAssign)]
        assert [n.target.id for n in fields]==['View_cls','view_args','skip_current_view','clear_history']
        init=ast.parse('def __init__(self, View_cls, view_args=None, skip_current_view=False, clear_history=False):\n self.View_cls=View_cls\n self.view_args=view_args\n self.skip_current_view=skip_current_view\n self.clear_history=clear_history').body[0]
        node.body=[n for n in node.body if n not in fields]
        node.body.insert(1,init)
    else:
        assert ast.unparse(node.bases[0])=='list[Destination]'
        node.bases=[ast.Name(id='list',ctx=ast.Load())]
    nodes.append(Types().visit(node))
module=ast.fix_missing_locations(ast.Module(body=nodes,type_ignores=[]))
header='# SPDX-License-Identifier: MIT\n# Copyright 2021 SeedSigner\n# Generated by tools/prepare_navigation.py from pinned original app classes.\n# Upstream notice: ../LICENSE.SeedSigner. Do not hand-edit.\n'
out=root/'app/seedsigner_port/navigation.py';out.write_text(header+ast.unparse(module)+'\n')
(root/'app/navigation-provenance.json').write_text(json.dumps({'application':lock,'classes':provenance,'transformations':['Remove type annotations/decorator dependency','Explicit dataclass-equivalent Destination constructor','BackStack generic base list[Destination] becomes list'],'outputSha256':hashlib.sha256(out.read_bytes()).hexdigest()},indent=2)+'\n')
print(out)
