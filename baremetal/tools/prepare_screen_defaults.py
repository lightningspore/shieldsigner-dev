"""Extract reviewed basic-screen defaults from pinned original dataclasses."""

import pyformat  # noqa: F401  (formats generated Python on write)
import ast
import hashlib
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
repo = root.parent
source = repo / 'dist/firmware/sources/lvgl/application'
lock = json.loads((repo / 'firmware/lvgl-app/sources.lock.json').read_text())['application']
assert (
    subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source, text=True).strip()
    == lock['commit']
)
path = source / 'src/seedsigner/gui/screens/screen.py'
components = source / 'src/seedsigner/gui/components.py'
constants = next(
    n
    for n in ast.parse(components.read_text()).body
    if isinstance(n, ast.ClassDef) and n.name == 'GUIConstants'
)
accent = next(
    ast.literal_eval(n.value)
    for n in constants.body
    if isinstance(n, ast.Assign)
    and any(isinstance(t, ast.Name) and t.id == 'ACCENT_COLOR' for t in n.targets)
)
fields = {
    'title',
    'show_back_button',
    'show_power_button',
    'selected_button',
    'is_bottom_list',
    'is_button_text_centered',
    'checked_buttons',
    'scroll_y_initial_offset',
    'top_nav_icon_name',
    'top_nav_icon_color',
    'button_selected_color',
}
classes = {n.name: n for n in ast.parse(path.read_text()).body if isinstance(n, ast.ClassDef)}


def defaults(name):
    node = classes[name]
    out = {}
    for base in node.bases:
        if isinstance(base, ast.Name) and base.id in classes:
            out.update(defaults(base.id))
    for n in node.body:
        if isinstance(n, ast.AnnAssign) and n.target.id in fields:
            if ast.unparse(n.value) == 'GUIConstants.ACCENT_COLOR':
                out[n.target.id] = accent
            else:
                out[n.target.id] = ast.literal_eval(n.value)
    return out


values = {
    name: defaults(name) for name in ('ButtonListScreen', 'LargeButtonScreen', 'MainMenuScreen')
}
out = root / 'app/seedsigner_port/screen_defaults.py'
out.write_text(
    '# SPDX-License-Identifier: MIT\n# Copyright 2021 SeedSigner; upstream notice: ../LICENSE.SeedSigner\n# Generated by tools/prepare_screen_defaults.py. Do not hand-edit.\nDEFAULTS = '
    + repr(values)
    + '\n'
)
(root / 'app/screen-defaults-provenance.json').write_text(
    json.dumps(
        {
            'application': lock,
            'sources': {
                str(p.relative_to(source)): hashlib.sha256(p.read_bytes()).hexdigest()
                for p in (path, components)
            },
            'reviewedFields': sorted(fields),
            'outputSha256': hashlib.sha256(out.read_bytes()).hexdigest(),
        },
        indent=2,
    )
    + '\n'
)
print(out)
