def nv12(rows):
    image = bytearray(b'\xff' * (640 * 480) + b'\x80' * (640 * 240))
    width = len(rows) * 6
    left = (640 - width) // 2
    top = (480 - width) // 2
    for y, row in enumerate(rows):
        line = b''.join(bytes([0 if bit == '1' else 255]) * 6 for bit in row)
        for j in range(6):
            p = (top + y * 6 + j) * 640 + left
            image[p : p + width] = line
    return image


class Pixels:
    def __init__(self, rows):
        self.frame = nv12(rows)
        self.active = False
        self.starts = 0
        self.stops = 0
        self.frames = 0

    def start_video_stream_mode(self):
        assert not self.active
        self.active = True
        self.starts += 1

    def read_video_stream(self):
        assert self.active
        self.frames += 1
        return self.frame

    def stop_video_stream_mode(self):
        if self.active:
            self.active = False
            self.stops += 1


