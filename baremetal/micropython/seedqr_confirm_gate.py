def pulse(key):
    ui.key(key, True)
    ui.key(key, False)


def choose(cfg, label):
    labels = [x if isinstance(x, str) else x['label'] for x in cfg['button_list']]
    for _ in range(labels.index(label)):
        pulse(18)
    pulse(10)


def nv12(rows):
    image = bytearray(b'\xff' * (640 * 480) + b'\x80' * (640 * 240))
    width = len(rows) * 6
    left = (640 - width) // 2
    top = (480 - width) // 2
    for y, row in enumerate(rows):
        line = b''.join(bytes([0 if bit == '1' else 255]) * 6 for bit in row)
        for j in range(6):
            offset = (top + y * 6 + j) * 640 + left
            image[offset : offset + width] = line
    return image


class Pixels:
    def __init__(self, rows, cancel):
        self.image = nv12(rows)
        self.cancel = cancel
        self.mask = 0
        self.starts = 0
        self.stops = 0
        self.frames = 0
        self.active = False
        self.pressed_at = None
        self.result = None

    def start_video_stream_mode(self):
        assert not self.active
        self.active = True
        self.starts += 1

    def read_video_stream(self):
        assert self.active
        self.frames += 1
        if self.cancel and self.frames == 2:
            self.mask = 4 if self.cancel == 'left' else 8
            self.pressed_at = int(clock.time() * 1000)
        if self.cancel and self.frames >= 3:
            time.sleep_ms(12)
        return self.image

    def stop_video_stream_mode(self):
        if self.active:
            decoder = Controller.get_instance().back_stack[-1].view.decoder
            self.result = (decoder.is_complete, decoder.is_seed, decoder.qr_type)
            self.active = False
            self.stops += 1
        self.mask = 0


class Driver:
    def __init__(self, mode, compact):
        self.mode = mode
        self.compact = compact
        self.prompts = 0
        self.zooms = 0
        self.success = 0
        self.errors = 0
        self.closed = False
        self.failure = None

    def __getattr__(self, name):
        return getattr(ui, name)

    def render(self, builder, encoded):
        try:
            self.checked(builder, encoded)
        except StopFlowBasedTest:
            raise
        except Exception as error:
            details = json.loads(encoded)
            self.failure = (
                builder,
                type(error).__name__,
                machine.exception_location(error),
                details.get('top_nav'),
                details.get('status_headline'),
                details.get('text'),
            )
            raise StopFlowBasedTest()

    def checked(self, builder, encoded):
        cfg = json.loads(encoded)
        ui.render(builder, encoded)
        c = Controller.get_instance()
        title = cfg['top_nav']['title']
        if builder == 'button_list_screen':
            if title == 'Backup Seed':
                choose(cfg, 'Export as SeedQR')
            elif title == 'Confirm SeedQR?':
                self.prompts += 1
                if self.prompts == 1:
                    choose(cfg, 'Confirm SeedQR')
                else:
                    assert self.mode != 'match' and self.prompts == 2
                    self.closed = True
                    choose(cfg, 'Done')
            else:
                assert title == seed.get_fingerprint() and c.storage.num_seeds() == 1
                assert not source.active and source.starts == source.stops == 1
                assert c.storage.seeds[0] is seed and seed.mnemonic_list == words
                if self.mode == 'match':
                    assert self.success == 1 and self.errors == 0
                else:
                    assert self.closed and self.success == 0
                pulse(20)
                pulse(10)
        elif builder == 'seed_transcribe_seedqr_format_screen':
            labels = [x if isinstance(x, str) else x['label'] for x in cfg['button_list']]
            choose(
                cfg,
                next(
                    x for x in labels if x.startswith('Compact:' if self.compact else 'Standard:')
                ),
            )
        elif builder == 'large_icon_status_screen':
            if cfg.get('status_headline') == 'SeedQR is your private key!':
                pulse(10)
            else:
                assert title == 'Confirm SeedQR' and not source.active
                if cfg.get('status_headline') == 'Success!':
                    assert self.mode == 'match'
                    self.success += 1
                else:
                    assert self.mode in ('wrong', 'nonseed', 'bad-checksum', 'address')
                    text = cfg['text']
                    assert (
                        ('does not match' in text)
                        if self.mode == 'wrong'
                        else ('could not be read' in text)
                    )
                    self.errors += 1
                pulse(10)
        elif builder == 'seed_transcribe_whole_qr_screen':
            pulse(10)
        elif builder == 'seed_transcribe_zoomed_qr_screen':
            self.zooms += 1
            pulse(10)
        elif builder == 'main_menu_screen':
            raise StopFlowBasedTest()
        else:
            raise ValueError('Unexpected confirmation screen')


